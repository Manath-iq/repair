const row = (k, v) => `<div class="nb__row"><span class="nb__k">${k}</span><span class="nb__v">${v}</span></div>`;

export function initNb(root) {
  if (!root) return;
  const chips = root.querySelector('[data-nb-chips]');
  const card = root.querySelector('[data-nb-card]');
  if (!chips || !card) return;

  chips.innerHTML = JK.map(([n], i) =>
    `<button class="chip${i === 1 ? ' on' : ''}" type="button" data-i="${i}">${n}</button>`).join('');

  const render = (i) => {
    const [n, fin, areas, done, from, note] = JK[i];
    card.innerHTML =
      row('Дом', `ЖК «${n}»`) +
      row('От застройщика', fin) +
      row('Типовые площади', areas) +
      row('Сдано квартир', String(done)) +
      row('Смета под ключ', from) +
      row('Срок на типовую двушку', '58–66 дней') +
      `<div class="nb__note"><b>что здесь особенного</b>${note}</div>`;
  };

  chips.addEventListener('click', (e) => {
    const b = e.target.closest('.chip');
    if (!b) return;
    chips.querySelectorAll('.chip').forEach((c) => c.classList.remove('on'));
    b.classList.add('on');
    render(+b.dataset.i);
  });

  render(1);
}
